// Embeds the fonts (TTF, converted unchanged from the woff2 latin subsets) and the dragon into src/assets.generated.ts,
// so the function bundle carries them: no file paths to resolve at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../assets/', import.meta.url);
const b64 = (name) => readFileSync(new URL(name, dir)).toString('base64');
const out = `// GENERATED by scripts/gen-assets.mjs: do not edit.\nexport const ANTON_400 = '${b64('Anton-400.ttf')}';\nexport const MONO_400 = '${b64('IBMPlexMono-400.ttf')}';\nexport const MONO_500 = '${b64('IBMPlexMono-500.ttf')}';\nexport const DRAGON_JPG = '${b64('dragon.jpg')}';\n`;
writeFileSync(new URL('../src/assets.generated.ts', import.meta.url), out);
console.log(`assets: ${out.length} bytes`);
